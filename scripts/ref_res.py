"""Regenerate and check app translations from the decoded 2.7.2 reference.

Usage: python -I scripts/ref_res.py <sync-strings|check-strings|check-colors> [--ref DIR] [--ref267 DIR]

--ref is the decoded reference res/ folder (default: %TEMP%/ref272/dec/res, see
tooling-setup.md); --ref267 is the decoded 2.6.7 one, used only by check-colors. The values-<lang>/strings.xml files written here are generated
and must not be edited by hand; rerun sync-strings instead.
"""
import argparse
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app", "src", "main", "res")
LANGUAGE_SCREEN = os.path.join(
    ROOT, "app", "src", "main", "java", "com", "quizango", "gallery", "ui", "settings", "LanguageScreen.kt")

# app_name: our brand name never comes from the reference.
# permanent_delete_Image_*: ScreenShortScreen reuses these keys with screenshot wording, while the
# 2.7.2 translations say "duplicate image".
# shortcut: kept English for those two keys, revisit when Phase 6 moves that screen to the reference screenshot keys.
SKIP = {"app_name", "permanent_delete_Image_title", "permanent_delete_Image_sub_title"}

# Date/time conversions keep their suffix (%1$tY vs %1$tm) so they stay distinct
SPEC_RE = re.compile(r"%((?:\d+\$)|<)?[-#+ 0,(]*\d*(\.\d+)?(?:[tT][a-zA-Z]|[a-zA-Z%])")
HEADER = "Generated by scripts/ref_res.py sync-strings from reference 2.7.2. Do not edit by hand."


def spec(element):
    """Which argument (1-based) each conversion consumes, so reordering is fine only when the bindings stay equal.

    Unindexed specs take the next argument, "%N$" names one, "%<" reuses the previous one ("bad" if none yet).
    """
    nxt, last, bound, literal = 1, 0, [], []
    for m in SPEC_RE.finditer("".join(element.itertext())):
        body = m.group(0)[1:]
        if body[-1] in "%n":
            literal.append(m.group(0))
            continue
        if m.group(1) == "<":
            idx = last or "bad"
            body = body[1:]
        elif m.group(1):
            idx, body = int(m.group(1)[:-1]), body[len(m.group(1)):]
        else:
            idx, nxt = nxt, nxt + 1
        last = idx if idx != "bad" else last
        bound.append((str(idx), body))
    return sorted(bound), sorted(literal)


def _selftest():
    one = lambda t: spec(ET.fromstring("<s>%s</s>" % t.replace("<", "&lt;")))
    assert one("%1$s of %2$d") == one("%2$d of %1$s") == ([("1", "s"), ("2", "d")], [])
    assert one("100%% done") == ([], ["%%"])
    assert one("%s: %d") != one("%d: %s")
    assert one("%1$s %<s") != one("%<s %1$s")
    assert norm("#fff", {}, {}) == "#ffffffff" and norm("#0066FF", {}, {}) == "#ff0066ff"
    assert norm("#1a002847", {}, {}) == "#1a002847" and norm("@android:color/transparent", {}, {}) == "#00000000"


AD_COLORS = {"dismiss_icon_grey_500", "dismiss_icon_grey_700", "im_browser_bg", "im_browser_loader_bg",
             "tt_bf161823", "background_dark", "background_light"}
FIXED = {"@android:color/transparent": "#00000000", "@android:color/white": "#ffffffff",
         "@android:color/black": "#ff000000"}


def load(path):
    if not os.path.isfile(path):
        return {}
    return {e.get("name"): (e.text or "").strip() for e in ET.parse(path).getroot() if e.tag == "color"}


def norm(value, table, light, depth=10):
    """Resolve @color references, then expand any hex spelling to #aarrggbb."""
    if value in FIXED:
        return FIXED[value]
    if value.startswith("@color/") and depth:
        name = value[7:]
        return norm(table.get(name, light.get(name, value)), table, light, depth - 1)
    h = value.lower()
    if re.fullmatch(r"#[0-9a-f]{3,4}", h):
        h = "#" + "".join(c * 2 for c in h[1:])
    if re.fullmatch(r"#[0-9a-f]{6}", h):
        h = "#ff" + h[1:]
    return h


def check_colors(ref, ref267):
    ours = load(os.path.join(RES, "values", "colors.xml"))
    ours_n = load(os.path.join(RES, "values-night", "colors.xml"))
    r_l, r_n = load(os.path.join(ref, "values", "colors.xml")), load(os.path.join(ref, "values-night", "colors.xml"))
    old = load(os.path.join(ref267, "values", "colors.xml"))
    if not r_l or not old:
        print("reference colors.xml missing or empty (--ref / --ref267)")
        return 2
    problems = []
    need = {n for n in r_l if n not in old} - AD_COLORS
    for d in os.listdir(RES):
        if d.startswith("drawable"):
            for f in os.listdir(os.path.join(RES, d)):
                if f.endswith(".xml"):
                    with open(os.path.join(RES, d, f), encoding="utf-8") as fh:
                        need.update(re.findall(r"@color/(\w+)", fh.read()))
    problems += ["missing: %s" % n for n in sorted(need - set(ours))]
    light = [n for n in ours if n in r_l]
    for n in light:
        if norm(ours[n], ours, ours) != norm(r_l[n], r_l, r_l):
            problems.append("differs (light): %s %s != %s" % (n, ours[n], r_l[n]))
    night = [n for n in r_n if n in ours]
    for n in night:
        if n not in ours_n:
            problems.append("missing (night): %s" % n)
        elif norm(ours_n[n], ours_n, ours) != norm(r_n[n], r_n, r_l):
            problems.append("differs (night): %s %s != %s" % (n, ours_n[n], r_n[n]))
    for n in ours_n:
        if n in r_l and n not in r_n and norm(ours_n[n], ours_n, ours) != norm(r_l[n], r_n, r_l):
            problems.append("extra night override: %s" % n)
    print("\n".join(problems))
    if problems:
        return 1
    print("colors: %d light / %d night names match 2.7.2" % (len(light), len(night)))
    return 0


def languages():
    with open(LANGUAGE_SCREEN, encoding="utf-8") as f:
        codes = re.findall(r'LanguageOption\("([a-z]+)"', f.read())
    return [c for c in codes if c != "en"]


def strings_of(path):
    return [e for e in ET.parse(path).getroot() if e.tag == "string"]


def render(ref, lang, notices):
    ours = strings_of(os.path.join(RES, "values", "strings.xml"))
    theirs = {e.get("name"): e for e in strings_of(os.path.join(ref, "values-" + lang, "strings.xml"))}
    lines = []
    for en in ours:
        key = en.get("name")
        ref_el = theirs.get(key)
        if key in SKIP or ref_el is None:
            continue
        if spec(ref_el) != spec(en):
            notices.append("kept English (format mismatch): %s/%s" % (lang, key))
            continue
        ref_el.tail = None
        lines.append("    " + ET.tostring(ref_el, encoding="unicode"))
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- %s -->\n<resources>\n%s\n</resources>\n'
            % (HEADER, "\n".join(lines)))


def target(lang):
    return os.path.join(RES, "values-" + lang, "strings.xml")


def sync_strings(ref):
    notices = []
    for lang in languages():
        text = render(ref, lang, notices)
        os.makedirs(os.path.dirname(target(lang)), exist_ok=True)
        with open(target(lang), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("%s: %d strings" % (lang, text.count("<string ")))
    print("\n".join(notices))
    return 0


def check_strings(ref):
    notices, stale = [], 0
    langs = languages()
    for lang in langs:
        want = render(ref, lang, notices)
        try:
            with open(target(lang), encoding="utf-8") as f:
                have = f.read()
        except FileNotFoundError:
            have = None
        if have != want:
            print("stale: values-%s/strings.xml" % lang)
            stale += 1
    print("\n".join(notices))
    if stale:
        return 1
    print("strings: %d languages up to date" % len(langs))
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=["sync-strings", "check-strings", "check-colors"])
    parser.add_argument("--ref", default=os.path.join(os.environ.get("TEMP", ""), "ref272", "dec", "res"))
    parser.add_argument("--ref267", default=os.path.join(os.environ.get("TEMP", ""), "ref267", "dec", "res"))
    args = parser.parse_args()
    _selftest()
    for d in (args.ref, args.ref267) if args.command == "check-colors" else (args.ref,):
        resource = "colors.xml" if args.command == "check-colors" else "strings.xml"
        if not os.path.isfile(os.path.join(d, "values", resource)):
            print("reference not decoded: %s (see tooling-setup.md)" % d)
            return 2
    if args.command == "check-colors":
        return check_colors(args.ref, args.ref267)
    return {"sync-strings": sync_strings, "check-strings": check_strings}[args.command](args.ref)


if __name__ == "__main__":
    sys.exit(main())
